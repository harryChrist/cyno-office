import type { ForYouDecisionStatus, ForYouItem, RetroView } from "@cyno/shared";
import { useCallback, useEffect, useMemo, useRef, useState } from "react";
import { api, describeError } from "../../../api/client";
import { useOfficeStore } from "../../../store/officeStore";
import { RuleCard } from "../../foryou/RuleCard";
import type { DecisionValues } from "../../foryou/ForYouCard";
import { ReportFrame } from "./ReportFrame";
import { retroApi } from "./retroApi";
import { askButtonLabel, askDisabledReason, badgeLabel, considerLine, groupLine, hasReady, ruleItems, waitingRules } from "./retroView";
import "../painel/painel.css";
import "./relatorios.css";
import "./retro.css";

type Note = { tone: "ok" | "warn" | "error"; text: string };

/**
 * "O que aprendemos": a retrospectiva da Gestão. Os padrões vêm do código (recusas, edições e falhas dos últimos 14 dias); as regras de
 * emoji, hashtag, tamanho e exclamação já nascem prontas por molde (sem IA). Só as de texto livre precisam do Maestro, e só pelo botão
 * com o custo à vista. Cada regra é um cartão que o dono aprova, edita ou recusa: nada entra no Cérebro sem o clique.
 */
export function RetroPanel({ workspaceId }: { workspaceId: string }) {
  const items = useOfficeStore((state) => state.forYou);
  const office = useOfficeStore((state) => state.office);
  const [view, setView] = useState<RetroView | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [note, setNote] = useState<Note | null>(null);
  const [busy, setBusy] = useState<"generate" | "ask" | null>(null);
  const [reportOpen, setReportOpen] = useState(false);
  const [reportHtml, setReportHtml] = useState<{ key: string; html: string } | null>(null);
  const [reportError, setReportError] = useState<string | null>(null);
  const autoGenerated = useRef(false);

  const rules = useMemo(() => ruleItems(items), [items]);
  const waiting = waitingRules(items);
  // O quadro refaz a conta quando os cartões mudam (um foi decidido, o Maestro mandou outro): sai a lista dos que esperam texto.
  const signature = rules.map((item) => `${item.id}:${item.status}`).join("|");

  useEffect(() => {
    let stale = false;
    retroApi
      .view(workspaceId)
      .then((next) => {
        if (stale) return;
        setView(next);
        setError(null);
      })
      .catch((failure: unknown) => {
        if (!stale) setError(describeError(failure));
      });
    return () => {
      stale = true;
    };
  }, [workspaceId, signature]);

  // Padrões com a regra pronta por molde: abre os cartões sozinho, uma vez (só código: não gasta nada e nada é aprovado).
  useEffect(() => {
    if (!view || autoGenerated.current || !hasReady(view)) return;
    autoGenerated.current = true;
    void retroApi
      .generate(workspaceId)
      .then((result) => {
        setView(result.view);
        if (result.opened > 0) setNote({ tone: "ok", text: `${result.opened} ${result.opened === 1 ? "regra pronta por molde" : "regras prontas por molde"}: abri ${result.opened === 1 ? "o cartão" : "os cartões"} abaixo (sem IA, nada foi aprovado).` });
      })
      .catch((failure: unknown) => setError(describeError(failure)));
  }, [view, workspaceId]);

  const reportKey = view ? `${view.period}|${view.stored[0]?.generatedAt ?? ""}|${signature}` : null;
  useEffect(() => {
    if (!reportOpen || !view || !reportKey || (reportHtml && reportHtml.key === reportKey)) return;
    let stale = false;
    retroApi
      .html(workspaceId, "latest")
      .then((html) => {
        if (!stale) setReportHtml({ key: reportKey, html });
      })
      .catch((failure: unknown) => {
        if (!stale) setReportError(describeError(failure));
      });
    return () => {
      stale = true;
    };
  }, [reportOpen, view, reportKey, reportHtml, workspaceId]);

  const generate = async () => {
    if (busy) return;
    setBusy("generate");
    setNote(null);
    try {
      const result = await retroApi.generate(workspaceId);
      setView(result.view);
      setReportHtml(null);
      setNote({ tone: "ok", text: result.opened > 0 ? `${result.opened} ${result.opened === 1 ? "cartão novo" : "cartões novos"} de regra por molde.` : "Procurei de novo: nenhum padrão novo por molde. A retrospectiva guardada foi atualizada." });
    } catch (failure) {
      setNote({ tone: "error", text: describeError(failure) });
    } finally {
      setBusy(null);
    }
  };

  const ask = async () => {
    if (busy || !view) return;
    setBusy("ask");
    setNote(null);
    try {
      const result = await retroApi.ask(workspaceId);
      setView(result.view);
      setNote({ tone: "ok", text: `Pedi ao Maestro ${result.asked === 1 ? "1 regra" : `${result.asked} regras`}. Os cartões aparecem aqui quando ele responder.` });
    } catch (failure) {
      setNote({ tone: "error", text: describeError(failure) });
    } finally {
      setBusy(null);
    }
  };

  const decide = useCallback(async (item: ForYouItem, status: ForYouDecisionStatus, values: DecisionValues) => {
    await api.decideForYou(item.id, { status, ...values });
  }, []);

  const names = useMemo(() => ({ agents: new Map(office?.agents.map((agent) => [agent.id, agent.name]) ?? []), rooms: new Map(office?.rooms.map((room) => [room.id, room.name]) ?? []) }), [office]);
  const disabledReason = view ? askDisabledReason(view) : undefined;
  const pendingRules = rules.filter((item) => item.status === "pendente");
  const decidedRules = rules.filter((item) => item.status !== "pendente");

  return (
    <div className="retro" data-testid="retro-panel">
      <header className="retro__head">
        <div>
          <h3 className="retro__title">
            O que aprendemos
            {waiting > 0 && (
              <span className="rel__badge" data-testid="retro-badge" title={badgeLabel(waiting)}>
                {waiting}
              </span>
            )}
          </h3>
          <p className="painel__sub" data-testid="retro-consider">
            {view ? considerLine(view) : "Procurando padrões nas suas decisões…"}
          </p>
        </div>
        <div className="retro__actions">
          <button type="button" className="ui-button ui-button--secondary ui-button--small" onClick={() => void generate()} disabled={busy !== null} aria-busy={busy === "generate"} title="Procura os padrões de novo (só código, sem IA) e abre os cartões das regras prontas por molde" data-testid="retro-generate">
            {busy === "generate" ? "Procurando…" : "Procurar de novo"}
          </button>
        </div>
      </header>

      {error && !view && (
        <p className="ui-error" role="alert" data-testid="retro-error">
          Não deu para carregar a retrospectiva. {error}
        </p>
      )}
      {note && (
        <p className={`rel__note rel__note--${note.tone}`} role={note.tone === "error" ? "alert" : "status"} data-testid="retro-note">
          {note.text}
        </p>
      )}

      {view && view.needsMaestro.length > 0 && (
        <section className="retro__ask" aria-label="Padrões que esperam texto" data-testid="retro-ask">
          <div>
            <h4 className="retro__h4">Padrões que precisam do Maestro para virar regra</h4>
            <ul className="retro__groups">
              {view.needsMaestro.map((group) => (
                <li key={group.id} data-testid="retro-group">
                  {groupLine(group)}
                </li>
              ))}
            </ul>
          </div>
          <div className="retro__ask-action">
            <button type="button" className="ui-button ui-button--primary" onClick={() => void ask()} disabled={busy !== null || disabledReason !== undefined} aria-busy={busy === "ask"} title={disabledReason} data-testid="retro-ask-button">
              {busy === "ask" ? "Pedindo…" : askButtonLabel(view)}
            </button>
            <p className="retro__cost">{disabledReason ?? "Uma mensagem só, com os grupos acima (em torno de 400 tokens cada). O custo é equivalente à API; nada é pedido sem o seu clique."}</p>
          </div>
        </section>
      )}

      {view && rules.length === 0 && view.needsMaestro.length === 0 && (
        <div className="rel__empty" data-testid="retro-empty">
          <p className="rel__empty-title">Nenhum padrão passou do limite ainda.</p>
          <p className="rel__empty-line">Um padrão vira regra com pelo menos 3 itens em 2 dias diferentes (ou 5 no total) nos últimos 14 dias. Conforme você aprova, edita e recusa, os padrões aparecem aqui.</p>
        </div>
      )}

      {pendingRules.length > 0 && (
        <section className="retro__rules" aria-label="Regras esperando o seu OK" data-testid="retro-pending">
          <h4 className="retro__h4">Esperando o seu OK ({pendingRules.length})</h4>
          <div className="retro__cards">
            {pendingRules.map((item) => (
              <RuleCard key={item.id} item={item} rule={item.rule!} agentName={names.agents.get(item.agentId)} roomName={names.rooms.get(item.roomId)} onDecide={decide} />
            ))}
          </div>
        </section>
      )}

      {decidedRules.length > 0 && (
        <section className="retro__rules" aria-label="Regras já decididas" data-testid="retro-decided">
          <h4 className="retro__h4">Já decididas</h4>
          <div className="retro__cards">
            {decidedRules.map((item) => (
              <RuleCard key={item.id} item={item} rule={item.rule!} agentName={names.agents.get(item.agentId)} roomName={names.rooms.get(item.roomId)} onDecide={decide} />
            ))}
          </div>
        </section>
      )}

      {view && view.impacts.length > 0 && (
        <section className="retro__box" data-testid="retro-impacts">
          <h4 className="retro__h4">Duas semanas depois</h4>
          <ul className="retro__lines">
            {view.impacts.map((impact) => (
              <li key={impact.itemId}>{impact.line}</li>
            ))}
          </ul>
        </section>
      )}

      {view && view.notices.length > 0 && (
        <section className="retro__box retro__box--warn" data-testid="retro-notices">
          <h4 className="retro__h4">Avisos (não viram regra)</h4>
          <ul className="retro__lines">
            {view.notices.map((notice) => (
              <li key={`${notice.kind}-${notice.agentId}`}>{notice.text}</li>
            ))}
          </ul>
        </section>
      )}

      {view && (
        <section className="retro__report">
          <button type="button" className="ui-button ui-button--secondary ui-button--small" aria-expanded={reportOpen} onClick={() => setReportOpen((current) => !current)} data-testid="retro-report-toggle">
            {reportOpen ? "Esconder o relatório da retrospectiva" : `Ver o relatório da retrospectiva (${view.period})`}
          </button>
          {reportOpen && reportError && (
            <p className="ui-error" role="alert">
              Não deu para abrir o relatório. {reportError}
            </p>
          )}
          {reportOpen && !reportHtml && !reportError && <p className="page__empty">Abrindo o relatório…</p>}
          {reportOpen && reportHtml && <ReportFrame html={reportHtml.html} title={`Retrospectiva ${view.period}`} />}
        </section>
      )}
    </div>
  );
}
