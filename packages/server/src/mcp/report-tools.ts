import { REPORT_KINDS, type ReportKind, type StoredReport } from "@cyno/shared";
import { z } from "zod";
import { renderRetroMarkdown, renderRetroText } from "../workspace/retro/render";
import type { RetroService } from "../workspace/retro/service";
import { renderReportMarkdown } from "../workspace/reports/render-md";
import { renderReportText } from "../workspace/reports/render-text";
import { defineTool, type McpTool } from "./protocol";

const DESCRIPTION =
  "The frozen management report of a closed period, computed by code (no AI, wakes nobody, nothing to recompute): the DAY summary (what each agent did, what comes next, what is blocked, the day's numbers against the same weekday last week), the WEEK review (goals hit or missed, deliveries, throughput, time to deliver, owner approval wait, rework and rejection, cost per delivery, quota, and the column 'vs. last week' with an arrow only when there are 5 or more samples on both sides) or the MONTH summary (the sum of the stored weeks), or the RETRO (kind 'retro': patterns found by code in the last 14 days of the owner's refusals, edits and failures, the rules proposed from them and their state: waiting for the owner, approved or refused, and two weeks after an approval how much the pattern dropped; rules enter the Brain only when the owner approves them). A closed period's report never changes; if it does not exist yet it is generated on the spot (the retro is only read: if none is stored, the tool says so). `period` defaults to 'latest' (the most recent closed one; today's day summary counts once the scheduled time has passed). Dollar figures are API-equivalent (the account is a subscription), always read them next to the quota. Use it for 'how was the week?', 'how was today?', 'what did Clara deliver this month?'. The default text is compact English; format 'markdown' returns the same report as the owner reads it (Portuguese tables).";

export const DESCRIPTION_PLATFORM = `${DESCRIPTION} For the Cyno: pass \`workspace\` for one workspace, or scope 'platform' (kind 'week' only) for the platform week: the sum of all workspaces and one block per workspace.`;

/** Os campos do `get_report` (iguais no Maestro e no Cyno; o Cyno soma `workspace` e `scope`). */
export const reportFields = {
  kind: z.enum([...REPORT_KINDS, "retro"]).describe("'day' (day summary), 'week' (week review), 'month' (month summary) or 'retro' (the retrospective: patterns, proposed rules and their state; `period` is a week like '2026-W46')"),
  period: z
    .string()
    .trim()
    .max(20)
    .optional()
    .describe("'latest' (default: the most recent closed period), a week like '2026-W46', a day like '2026-11-10' or a month like '2026-11' (the month holds the weeks whose Thursday falls in it)"),
  format: z.enum(["text", "markdown"]).optional().describe("'text' (default, compact English for you) or 'markdown' (the report as the owner reads it, in Portuguese)"),
};

export type ReportInput = { kind: ReportKind | "retro"; period?: string | undefined; format?: "text" | "markdown" | undefined };

/** A retrospectiva (`kind: "retro"`): a guardada mais nova, ou a de uma semana. Só lê: nunca gera uma nem abre cartão de regra. */
export type RetroReader = Pick<RetroService, "ensure">;

/** O texto do relatório de um período (guardado ou gerado na hora). Período inválido: joga o motivo. */
export async function reportText(ensure: (kind: ReportKind, period: string | undefined) => Promise<StoredReport | undefined>, input: ReportInput, retro?: RetroReader): Promise<string> {
  if (input.kind === "retro") {
    if (!retro) throw new Error("The retrospective is not available here.");
    const found = await retro.ensure(input.period);
    if (!found) {
      const latest = !input.period || input.period.trim() === "latest";
      if (latest) return "No retrospective is stored yet. This tool only reads: it never generates one or opens rule cards. The retrospective is generated by the weekly review schedule or by the owner's button on the learnings page.";
      throw new Error(`"${input.period}" is not a stored retrospective week (use "latest" or a week like "2026-W46").`);
    }
    return input.format === "markdown" ? renderRetroMarkdown(found) : renderRetroText(found);
  }
  const report = await ensure(input.kind, input.period);
  if (!report) throw new Error(`"${input.period}" is not a valid ${input.kind} period (use "latest", ${input.kind === "day" ? '"2026-11-10"' : input.kind === "week" ? '"2026-W46"' : '"2026-11"'}).`);
  return input.format === "markdown" ? renderReportMarkdown(report) : renderReportText(report);
}

/** `get_report` do Maestro: o relatório do próprio workspace. */
export function maestroReportTool(deps: { ensure: (kind: ReportKind, period: string | undefined) => Promise<StoredReport | undefined>; retro?: RetroReader }): McpTool {
  return defineTool({
    name: "get_report",
    description: DESCRIPTION,
    input: z.object(reportFields),
    call: async (input) => {
      try {
        return { text: await reportText(deps.ensure, input, deps.retro) };
      } catch (error) {
        return { text: error instanceof Error ? error.message : String(error), isError: true };
      }
    },
  });
}
